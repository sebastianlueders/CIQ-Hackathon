def get_hardware_preset_for_model(model_id: str) -> dict[str, Any] | None:
    cleaned = model_id.strip()
    for k, v in COMPANY_HARDWARE_PRESETS.items():
        if k.lower() == cleaned.lower():
            return v
    return None

_MIXTRAL_RE = re.compile(r"(\d+)\s*[xX]\s*(\d+(?:\.\d+)?)\s*[bB]")
_ACTIVE_RE = re.compile(r"[-_][aA](\d+(?:\.\d+)?)\s*[bB]\b")
_ACTIVE_M_RE = re.compile(r"[-_][aA](\d+)\s*[mM]\b")
_PARAMS_B_RE = re.compile(r"(?:^|[-_/])(\d+(?:\.\d+)?)\s*[bB](?:$|[-_/])")


def _slugify(text: str) -> str:
    clean = re.sub(r"[^a-zA-Z0-9]+", "-", text.strip()).strip("-").lower()
    return clean[:48] or "custom-model"


def infer_model_profile(model_id: str, node_mem_gb: int = 104) -> ModelProfileConfig:
    """Resolve exact preset or infer architecture, parameter scale, MoE routing, and node sizing
    for ANY HuggingFace repo ID (`org/model`) or local `/models/...` path."""
    cleaned = model_id.strip() or "Qwen/Qwen3-Coder-30B-A3B-Instruct"
    lower = cleaned.lower()

    for preset in MODEL_CATALOG:
        if preset["id"].lower() == lower or preset["label"].lower() == lower:
            bf16_gb = round(float(preset["total_params_b"]) * 1.92, 1)
            min_nodes = 1 if bf16_gb <= (node_mem_gb - 18) else 2
            subpath = cleaned.lstrip("/").removeprefix("models/")
            return ModelProfileConfig(
                name=cleaned,
                weights_subpath=subpath,
                architecture=preset["architecture"],
                total_params_b=float(preset["total_params_b"]),
                active_params_b=float(preset["active_params_b"]),
                vocab_size=int(preset["vocab_size"]),
                hidden_size=int(preset["hidden_size"]),
                num_layers=int(preset["num_layers"]),
                num_experts=int(preset["num_experts"]),
                top_k_experts=int(preset["top_k_experts"]),
                bf16_footprint_gb=bf16_gb,
                min_nodes_required=min_nodes,
            )

    # Dynamic inference for arbitrary custom model IDs
    mix_match = _MIXTRAL_RE.search(cleaned)
    act_match = _ACTIVE_RE.search(cleaned)
    act_m_match = _ACTIVE_M_RE.search(cleaned)
    param_matches = _PARAMS_B_RE.findall(cleaned)

    is_moe = bool(
        mix_match
        or act_match
        or act_m_match
        or any(
            tok in lower
            for tok in (
                "moe",
                "mixtral",
                "deepseek-v2",
                "deepseek-v3",
                "deepseek-coder-v2",
                "qwen3-coder-30b",
                "qwen3-coder-80b",
                "dbrx",
                "arctic",
                "jamba",
                "scout",
                "maverick",
            )
        )
    )

    if mix_match:
        n_exp = int(mix_match.group(1))
        per_exp = float(mix_match.group(2))
        total_b = round(n_exp * per_exp * 0.84, 1)
        active_b = round(2.0 * per_exp, 1)
        top_k = 2
    elif param_matches:
        total_b = float(param_matches[0])
        if act_match:
            active_b = float(act_match.group(1))
        elif act_m_match:
            active_b = round(float(act_m_match.group(1)) / 1000.0, 2)
        elif is_moe:
            active_b = round(max(1.2, total_b * 0.14), 1)
        else:
            active_b = total_b
        n_exp = 64 if is_moe else 1
        top_k = 6 if is_moe else 1
    else:
        total_b = 16.0 if is_moe else 8.0
        active_b = 2.5 if is_moe else 8.0
        n_exp = 64 if is_moe else 1
        top_k = 6 if is_moe else 1

    if "qwen" in lower or "qwq" in lower:
        vocab = 151936
        arch = "qwen_moe" if is_moe else "qwen_dense"
    elif "llama" in lower or "nemotron" in lower:
        vocab = 128256
        arch = "llama_moe" if is_moe else "llama_dense"
    elif "deepseek" in lower:
        vocab = 102400
        arch = "deepseek_moe" if is_moe else "deepseek_dense"
    elif "gemma" in lower:
        vocab = 256000
        arch = "gemma_dense"
    elif "phi" in lower:
        vocab = 100352
        arch = "phi_moe" if is_moe else "phi3_dense"
    elif "granite" in lower or "starcoder" in lower:
        vocab = 49152
        arch = "granite_moe" if is_moe else "granite_dense"
    elif "mistral" in lower or "codestral" in lower or "devstral" in lower or "mixtral" in lower:
        vocab = 131072 if ("nemo" in lower or "small-24b" in lower or "devstral" in lower) else 32768
        arch = "mixtral_moe" if is_moe else "mistral_dense"
    elif "command" in lower:
        vocab = 256000
        arch = "command_r_dense"
    else:
        vocab = 65536
        arch = "transformer_moe" if is_moe else "transformer_dense"

    hidden = (
        1536
        if active_b <= 1.8
        else (2048 if active_b <= 4.0 else (4096 if active_b <= 16.0 else (5120 if active_b <= 36.0 else 8192)))
    )
    layers = 28 if total_b <= 9.0 else (40 if total_b <= 20.0 else (48 if total_b <= 36.0 else 64))
    bf16_gb = round(total_b * 1.95, 1)
    min_nodes = 1 if bf16_gb <= (node_mem_gb - 16) else 2
    subpath = cleaned.lstrip("/").removeprefix("models/")

    return ModelProfileConfig(
        name=cleaned,
        weights_subpath=subpath,
        architecture=arch,
        total_params_b=total_b,
        active_params_b=active_b,
        vocab_size=vocab,
        hidden_size=hidden,
        num_layers=layers,
        num_experts=n_exp,
        top_k_experts=top_k,
        bf16_footprint_gb=bf16_gb,
        min_nodes_required=min_nodes,
    )


def enrich_catalog_for_cluster(
    node_mem_gb: int = 96,
    staged_models: set[str] | None = None,
    staging_in_progress: set[str] | None = None,
) -> list[dict[str, Any]]:
    """Return MODEL_CATALOG enriched with hardware fit, VAST pre-load state, and company sm_121 preset status."""
    known_loaded = {m.lower() for m in DEFAULT_PRELOADED_VAST_MODELS}
    if staged_models:
        known_loaded |= {m.lower() for m in staged_models}
    in_flight = {m.lower() for m in (staging_in_progress or set())}

    enriched: list[dict[str, Any]] = []
    for item in MODEL_CATALOG:
        prof = infer_model_profile(item["id"], node_mem_gb=node_mem_gb)
        preset = get_hardware_preset_for_model(item["id"])
        id_low = item["id"].lower()
        is_preloaded = id_low in known_loaded
        is_staging = id_low in in_flight
        est_load_seconds = max(15, int(round((prof.bf16_footprint_gb / 1.45))))
        client_local_fit = (
            "Laptop / Edge Ready (4-8 GB RAM)"
            if prof.total_params_b <= 4.5
            else (
                "Workstation Ready (16-32 GB RAM)"
                if prof.total_params_b <= 16.0
                else (
                    "1x GB10 Server / Mac Studio (32-64 GB)"
                    if prof.min_nodes_required == 1
                    else "2x GB10 Fuzzball Cluster (FSDP / TP2)"
                )
            )
        )
        enriched.append(
            {
                **item,
                "bf16_footprint_gb": prof.bf16_footprint_gb,
                "fp8_footprint_gb": round(prof.total_params_b * 1.02, 1),
                "nvfp4_footprint_gb": round(prof.total_params_b * 0.56, 1),
                "min_nodes_required": prof.min_nodes_required,
                "is_moe": prof.num_experts > 1,
                "client_deployment_tier": client_local_fit,
                "vast_state": "loading" if is_staging else ("preloaded" if is_preloaded else "needs_load"),
                "preloaded_on_vast": is_preloaded,
                "est_vast_load_seconds": est_load_seconds,
                "has_hardware_preset": preset is not None,
                "hardware_preset": preset,
            }
        )
    return enriched


