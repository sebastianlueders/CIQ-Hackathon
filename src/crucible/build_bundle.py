def _extract_model_from_fuzzfile(fuzzfile_yaml: str) -> str:
    for ln in fuzzfile_yaml.splitlines():
        if "Base Model" in ln and ":" in ln:
            return ln.split(":", 1)[1].split("(")[0].strip()
    return "Qwen/Qwen3-Coder-30B-A3B-Instruct"


def create_build_bundle_zip_bytes(
    summary: dict[str, Any],
    run_dir: Path,
    company_name: str = "Apex Dynamics",
) -> bytes:
    artifacts = build_artifact_texts(summary, run_dir, company_name=company_name)
    packed_dir = run_dir / "dataset_packed"

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for rel_name, content in artifacts.items():
            if rel_name == "data/teacher_sft_train.jsonl" and (packed_dir / "teacher_sft_train.jsonl").exists():
                continue
            info = zipfile.ZipInfo(rel_name)
            info.external_attr = (0o755 << 16) if rel_name.endswith((".sh", ".py")) else (0o644 << 16)
            zf.writestr(info, content)

        # Include actual train, val, held_out (plus test.jsonl alias), Teacher SFT splits, and manifests
        for fname in (
            "train.jsonl",
            "val.jsonl",
            "held_out.jsonl",
            "dataset_manifest.json",
            "teacher_sft_train.jsonl",
            "teacher_sft_val.jsonl",
            "teacher_sft_test.jsonl",
            "teacher_curriculum_manifest.json",
        ):
            fpath = packed_dir / fname
            if fpath.exists():
                raw = fpath.read_bytes()
                zf.writestr(f"data/{fname}", raw)
                if fname == "held_out.jsonl":
                    zf.writestr("data/test.jsonl", raw)

        audit_path = run_dir / "privacy_audit.jsonl"
        if audit_path.exists():
            zf.writestr("privacy_audit.jsonl", audit_path.read_bytes())

    return buf.getvalue()
