"""Self-contained downloadable build package generator (`build_bundle.zip`).

Packages everything a user needs to deploy or re-run their exact Crucible-optimized model
and custom/preset dataset on CIQ Fuzzball (`use: team3`) or any local GPU server:
  - `fuzzfile.yaml`
  - `configs/train_recipe.yaml`
  - `configs/vllm_serve.yaml`
  - `scripts/launch_fuzzball.sh`
  - `scripts/train_and_serve_local.py`
  - `data/train.jsonl`, `data/val.jsonl`, `data/test.jsonl`, `data/held_out.jsonl`, `data/dataset_manifest.json`
  - `BUILD_REPORT.md`
"""

from __future__ import annotations

import io
import json
import zipfile
from pathlib import Path
from typing import Any

import yaml


def build_artifact_texts(summary: dict[str, Any], run_dir: Path) -> dict[str, str]:
    cluster = summary["cluster"]
    team_prov = cluster["vast"].get("provisioner") or cluster.get("definition_id") or "team3"
    vol_name = cluster["vast"].get("persistent_volume_name") or "runs"
    manifest = summary["dataset_manifest"]
    dataset_name = manifest.get("dataset_name", "custom-dataset")

    sa = summary["stage_a"]
    sb = summary["stage_b"]
    sc = summary["stage_c"]
    win_recipe = sa["winning_recipe"]
    win_train = sb["winning_candidate"]
    win_serve = next(
        (o for o in sc["outcomes"] if o["label"] == sc["winning_label"]),
        sc["outcomes"][0],
    )
    model_id = summary.get("model_profile", {}).get("name") or _extract_model_from_fuzzfile(
        summary.get("turnkey_fuzzfile", "")
    )

    fuzzfile_yaml = summary["turnkey_fuzzfile"]

    train_recipe_cfg = {
        "model_id": model_id,
        "dataset": {
            "name": dataset_name,
            "train_split": "data/train.jsonl",
            "validation_split": "data/val.jsonl",
            "held_out_test_split": "data/test.jsonl",
            "manifest_sha256": manifest.get("manifest_sha256", ""),
            "split_document_counts": manifest.get("split_file_counts", {}),
            "split_chunk_counts": manifest.get("split_chunk_counts", {}),
        },
        "lora_recipe": win_recipe,
        "training_performance": win_train,
        "measured_metrics": {
            "baseline_test_perplexity": sa["base_held_out_perplexity"],
            "tuned_test_perplexity": sa["winning_summary"]["held_out_perplexity"],
            "baseline_test_loss": sa["base_held_out_loss"],
            "tuned_test_loss": sa["winning_summary"]["held_out_eval_loss"],
            "training_speedup_x": sb["overall_speedup_x"],
            "sm121_single_node_kernel_speedup_x": sb["single_node_kernel_speedup_x"],
        },
    }
    train_recipe_yaml = yaml.safe_dump(train_recipe_cfg, sort_keys=False)

    quant_flag = (
        "--dtype bfloat16"
        if win_serve["precision"] == "BF16"
        else (
            "--quantization fp8 --kv-cache-dtype fp8"
            if win_serve["precision"] == "FP8"
            else "--quantization modelopt --kv-cache-dtype fp8"
        )
    )
    vllm_serve_cfg = {
        "model_id": model_id,
        "adapter_path": "./outputs/lora_adapter",
        "precision": win_serve["precision"],
        "tensor_parallel_size": win_serve["tensor_parallel"],
        "replicas": win_serve["replicas"],
        "max_num_seqs": win_serve["max_num_seqs"],
        "use_sm121_low_prec_decode_kernel": win_serve["use_low_prec_decode_kernel"],
        "vllm_command": (
            f"vllm serve {model_id} --enable-lora "
            f"--lora-modules tuned=./outputs/lora_adapter "
            f"--tensor-parallel-size {win_serve['tensor_parallel']} "
            f"--max-num-seqs {win_serve['max_num_seqs']} "
            f"--attention-backend TRITON_ATTN {quant_flag} --port 8000"
        ),
        "verified_quality_gate": {
            "throughput_tokens_per_sec": win_serve["throughput_tokens_per_sec"],
            "p99_latency_ms": win_serve["p99_latency_ms"],
            "test_perplexity_regression_pct": win_serve["perplexity_regression_pct"],
            "completion_pass_rate": win_serve["completion_pass_rate"],
        },
    }
    vllm_serve_yaml = yaml.safe_dump(vllm_serve_cfg, sort_keys=False)

    launch_fuzzball_sh = f"""#!/usr/bin/env bash
# Turnkey CIQ Fuzzball launcher generated by Crucible
# Model   : {model_id}
# Dataset : {dataset_name} (bundled under ./data/)
# Team    : {team_prov} (VAST volume '{vol_name}')
set -euo pipefail

BUNDLE_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")/.." && pwd)"
cd "$BUNDLE_DIR"

TEAM_PROVISIONER="${{CRUCIBLE_TEAM:-{team_prov}}}"
VOLUME_NAME="${{CRUCIBLE_VOLUME:-{vol_name}}}"

echo "[crucible-build] Ensuring VAST volume '${{VOLUME_NAME}}' exists on provisioner '${{TEAM_PROVISIONER}}'..."
fuzzball volume list "${{TEAM_PROVISIONER}}" | grep -qw "${{VOLUME_NAME}}" || \\
  fuzzball volume create "${{TEAM_PROVISIONER}}" "${{VOLUME_NAME}}" || true

echo "[crucible-build] Validating turnkey Fuzzfile..."
fuzzball workflow validate "${{BUNDLE_DIR}}/fuzzfile.yaml"

echo "[crucible-build] Submitting workflow to CIQ Fuzzball (queues automatically if GPUs are busy)..."
WF_ID="$(fuzzball workflow start "${{BUNDLE_DIR}}/fuzzfile.yaml" --name "crucible-{dataset_name}" | tail -1)"
echo "[crucible-build] Workflow submitted: ${{WF_ID}}"
echo "[crucible-build] Monitor queue & GPU execution with:"
echo "  fuzzball workflow describe ${{WF_ID}}"
echo "  fuzzball workflow log ${{WF_ID}} train-lora -f"
"""

    local_runner_py = f'''#!/usr/bin/env python3
"""Standalone local LoRA fine-tuning + held-out test verification script generated by Crucible."""
import json
import math
from pathlib import Path

MODEL_ID = {model_id!r}
RECIPE = {json.dumps(win_recipe, indent=2)}
TRAIN_PERF = {json.dumps(win_train, indent=2)}
SERVE_CONFIG = {json.dumps(vllm_serve_cfg["vllm_command"])}


def load_chunks(split_path: Path) -> list[list[int]]:
    rows = []
    for line in split_path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line)["input_ids"])
    return rows


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    train_chunks = load_chunks(root / "data" / "train.jsonl")
    val_chunks = load_chunks(root / "data" / "val.jsonl")
    test_chunks = load_chunks(root / "data" / "test.jsonl")
    print(f"Loaded splits for {{MODEL_ID}}: train={{len(train_chunks)}}, val={{len(val_chunks)}}, test={{len(test_chunks)}}")

    import torch
    from peft import LoraConfig, get_peft_model
    from transformers import AutoModelForCausalLM

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = torch.bfloat16 if torch.cuda.is_available() else torch.float32
    model = AutoModelForCausalLM.from_pretrained(MODEL_ID, torch_dtype=dtype).to(device)
    if TRAIN_PERF.get("activation_checkpointing") and hasattr(model, "gradient_checkpointing_enable"):
        model.gradient_checkpointing_enable()

    lora_cfg = LoraConfig(
        r=RECIPE["lora_rank"],
        lora_alpha=RECIPE["lora_alpha"],
        target_modules=RECIPE["target_modules"],
        lora_dropout=0.0,
        bias="none",
        task_type="CAUSAL_LM",
    )
    model = get_peft_model(model, lora_cfg)
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=RECIPE["lr"])

    for step, seq in enumerate(train_chunks[:120], start=1):
        ids = torch.tensor([seq[: RECIPE["seq_len"]]], dtype=torch.long, device=device)
        loss = model(input_ids=ids[:, :-1], labels=ids[:, 1:]).loss
        opt.zero_grad()
        loss.backward()
        opt.step()
        if step % 10 == 0 or step == 1:
            print(f"step={{step}} train_loss={{float(loss.item()):.4f}}")

    model.eval()
    with torch.no_grad():
        test_losses = []
        for seq in test_chunks[:16]:
            ids = torch.tensor([seq[: RECIPE["seq_len"]]], dtype=torch.long, device=device)
            test_losses.append(float(model(input_ids=ids[:, :-1], labels=ids[:, 1:]).loss.item()))
        mean_test = sum(test_losses) / max(1, len(test_losses))
        print(f"Held-out test loss={{mean_test:.4f}} | test perplexity={{math.exp(min(mean_test, 20.0)):.3f}}")

    out_dir = root / "outputs" / "lora_adapter"
    out_dir.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(str(out_dir))
    print(f"Saved tuned LoRA adapter -> {{out_dir}}")
    print(f"Serve with vLLM:\\n  {{SERVE_CONFIG}}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

    report_path = run_dir / "run_report.md"
    build_report_md = (
        report_path.read_text(encoding="utf-8")
        if report_path.exists()
        else f"# Crucible Build Report — `{model_id}` on `{dataset_name}`\n"
    )

    return {
        "fuzzfile.yaml": fuzzfile_yaml,
        "configs/train_recipe.yaml": train_recipe_yaml,
        "configs/vllm_serve.yaml": vllm_serve_yaml,
        "scripts/launch_fuzzball.sh": launch_fuzzball_sh,
        "scripts/train_and_serve_local.py": local_runner_py,
        "BUILD_REPORT.md": build_report_md,
    }


def _extract_model_from_fuzzfile(fuzzfile_yaml: str) -> str:
    for ln in fuzzfile_yaml.splitlines():
        if "Base Model" in ln and ":" in ln:
            return ln.split(":", 1)[1].split("(")[0].strip()
    return "Qwen/Qwen3-Coder-30B-A3B-Instruct"


def create_build_bundle_zip_bytes(summary: dict[str, Any], run_dir: Path) -> bytes:
    artifacts = build_artifact_texts(summary, run_dir)
    packed_dir = run_dir / "dataset_packed"

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for rel_name, content in artifacts.items():
            info = zipfile.ZipInfo(rel_name)
            info.external_attr = (0o755 << 16) if rel_name.endswith((".sh", ".py")) else (0o644 << 16)
            zf.writestr(info, content)

        # Include actual train, val, held_out (plus test.jsonl alias) and manifest
        for fname in ("train.jsonl", "val.jsonl", "held_out.jsonl", "dataset_manifest.json"):
            fpath = packed_dir / fname
            if fpath.exists():
                raw = fpath.read_bytes()
                zf.writestr(f"data/{fname}", raw)
                if fname == "held_out.jsonl":
                    zf.writestr("data/test.jsonl", raw)

        audit_path = run_dir / "privacy_audit.jsonl"
        if audit_path.exists():
            zf.writestr("privacy_audit.jsonl", audit_path.read_bytes())

    return buf.getvalue()
