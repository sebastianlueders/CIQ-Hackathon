def load_chunks(split_path: Path) -> list[list[int]]:
    rows = []
    for line in split_path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line)["input_ids"])
    return rows


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    train_chunks = load_chunks(root / "data" / "train.jsonl")
    val_chunks = load_chunks(root / "data" / "val.jsonl")
    test_chunks = load_chunks(root / "data" / "test.jsonl")
    print(f"Loaded splits for {{MODEL_ID}}: train={{len(train_chunks)}}, val={{len(val_chunks)}}, test={{len(test_chunks)}}")

    import torch
    from peft import LoraConfig, get_peft_model
    from transformers import AutoModelForCausalLM

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = torch.bfloat16 if torch.cuda.is_available() else torch.float32
    model = AutoModelForCausalLM.from_pretrained(MODEL_ID, torch_dtype=dtype).to(device)
    if TRAIN_PERF.get("activation_checkpointing") and hasattr(model, "gradient_checkpointing_enable"):
        model.gradient_checkpointing_enable()

    lora_cfg = LoraConfig(
        r=RECIPE["lora_rank"],
        lora_alpha=RECIPE["lora_alpha"],
        target_modules=RECIPE["target_modules"],
        lora_dropout=0.0,
        bias="none",
        task_type="CAUSAL_LM",
    )
    model = get_peft_model(model, lora_cfg)
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=RECIPE["lr"])

    for step, seq in enumerate(train_chunks[:120], start=1):
        ids = torch.tensor([seq[: RECIPE["seq_len"]]], dtype=torch.long, device=device)
        loss = model(input_ids=ids[:, :-1], labels=ids[:, 1:]).loss
        opt.zero_grad()
        loss.backward()
        opt.step()
        if step % 10 == 0 or step == 1:
            print(f"step={{step}} train_loss={{float(loss.item()):.4f}}")

    model.eval()
    with torch.no_grad():
        test_losses = []
        for seq in test_chunks[:16]:
            ids = torch.tensor([seq[: RECIPE["seq_len"]]], dtype=torch.long, device=device)
            test_losses.append(float(model(input_ids=ids[:, :-1], labels=ids[:, 1:]).loss.item()))
        mean_test = sum(test_losses) / max(1, len(test_losses))
        print(f"Held-out test loss={{mean_test:.4f}} | test perplexity={{math.exp(min(mean_test, 20.0)):.3f}}")

    out_dir = root / "outputs" / "lora_adapter"
    out_dir.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(str(out_dir))
    print(f"Saved tuned LoRA adapter -> {{out_dir}}")
    print(f"Serve with vLLM:\\n  {{SERVE_CONFIG}}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
