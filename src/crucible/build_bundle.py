        "    for (int ii = 0; ii < inum; ++ii) {{\\n"
        "        const int i = ilist[ii];\\n"
        "        double fx = 0.0, fy = 0.0, fz = 0.0;\\n"
        "        #pragma omp simd reduction(+:fx,fy,fz)\\n"
        "        for (int jj = 0; jj < numneigh[i]; ++jj) {{\\n"
